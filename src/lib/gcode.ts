export function textToPathPoints(shape: TextShape): Point[][] {
  const fontId = (shape as any).font || 'cnc-stroke';
  if (isCustomFont(fontId)) {
    return fontToPathPoints(shape.text, shape.x, shape.y, shape.fontSize, fontId);
  }
  if (isSystemFont(fontId)) {
    return systemFontToPathPoints(shape.text, shape.x, shape.y, shape.fontSize, fontId);
  }
  const paths: Point[][] = [];
  const charWidth = shape.fontSize * 0.6;
  const charHeight = shape.fontSize;
  const text = shape.text.toUpperCase();

  for (let ci = 0; ci < text.length; ci++) {
    const ch = text[ci];
    const charPaths = TEXT_CHAR_PATHS[ch];
    if (!charPaths) continue;

    const offsetX = shape.x + ci * charWidth;
    const offsetY = shape.y;

    for (const path of charPaths) {
      const pts: Point[] = path.map((p) => ({
        x: offsetX + (p.x / 5) * charWidth,
        y: offsetY - (p.y / 10) * charHeight,
      }));
      paths.push(pts);
    }
  }

  return paths;
}

export function calculateVBitDepth(widthBetweenLines: number, bitAngleDegrees: number): number {
  const halfAngleRadians = (bitAngleDegrees / 2) * (Math.PI / 180);
  const absoluteDepth = (widthBetweenLines / 2) / Math.tan(halfAngleRadians);
  return parseFloat(absoluteDepth.toFixed(3));
}

export function generateGCode(shapes: Shape[], settings: CamSettings): string[] {
  const lines: string[] = [];
  const unit = settings.units === 'mm' ? 'G21' : 'G20';

  lines.push('; Generated by WebCNC');
  lines.push(unit);
  lines.push('G90');
  lines.push('G17');
  lines.push('G94');
  lines.push(`M3 S${settings.spindleSpeed}`);
  lines.push(`G0 Z${settings.safeHeight.toFixed(3)}`);

  const passCount = Math.ceil(settings.cutDepth / settings.passDepth);

  for (const shape of shapes) {
    if (shape.type === 'dimension') continue;
    if (settings.cutType === 'drill') {
      generateDrillGCode(shape, settings, lines);
    } else if (settings.cutType === 'pocket') {
      generatePocketGCode(shape, settings, lines, passCount);
    } else if (settings.cutType === 'vcarve') {
      generateVCarveGCode(shape, settings, lines);
    } else {
      generateProfileGCode(shape, settings, lines, passCount);
    }
  }

  lines.push('M5');
  lines.push('M30');
  return lines;
}

function generateProfileGCode(shape: Shape, settings: CamSettings, lines: string[], passCount: number) {
  if (shape.type === 'text') {
    const charPaths = textToPathPoints(shape);
    for (const path of charPaths) {
      if (path.length < 2) continue;
      cutPath(path, settings, lines, passCount, true);
    }
    return;
  }

  let pathPoints = shapeToPathPoints(shape);
  if (pathPoints.length < 2) return;

  pathPoints = offsetPath(pathPoints, settings.bitDiameter / 2);
  const isClosed = shape.type === 'rect' || shape.type === 'circle' || (shape.type === 'path' && pathPoints.length > 2);
  cutPath(pathPoints, settings, lines, passCount, isClosed);
}

function generatePocketGCode(shape: Shape, settings: CamSettings, lines: string[], passCount: number) {
  const b = shapeBounds(shape);
  const margin = settings.bitDiameter / 2;
  const minX = b.minX + margin;
  const minY = b.minY + margin;
  const maxX = b.maxX - margin;
  const maxY = b.maxY - margin;
  const stepOver = settings.bitDiameter * 0.7;

  if (maxX - minX < stepOver || maxY - minY < stepOver) return;

  for (let pass = 1; pass <= passCount; pass++) {
    const z = -(Math.min(pass * settings.passDepth, settings.cutDepth));
    let y = minY;
    let leftToRight = true;

    lines.push(`G0 X${minX.toFixed(3)} Y${minY.toFixed(3)}`);
    lines.push(`G1 Z${z.toFixed(3)} F${settings.plungeRate}`);

    while (y <= maxY) {
      const startX = leftToRight ? minX : maxX;
      const endX = leftToRight ? maxX : minX;
      lines.push(`G1 X${endX.toFixed(3)} Y${y.toFixed(3)} F${settings.feedRate}`);
      y += stepOver;
      if (y <= maxY) {
        lines.push(`G1 X${endX.toFixed(3)} Y${y.toFixed(3)} F${settings.feedRate}`);
        lines.push(`G1 X${startX.toFixed(3)} Y${y.toFixed(3)} F${settings.feedRate}`);
        y += stepOver;
      }
      leftToRight = !leftToRight;
    }

    lines.push(`G0 Z${settings.safeHeight.toFixed(3)}`);
  }
}

function generateDrillGCode(shape: Shape, settings: CamSettings, lines: string[]) {
  const b = shapeBounds(shape);
  const cx = (b.minX + b.maxX) / 2;
  const cy = (b.minY + b.maxY) / 2;

  lines.push(`G0 X${cx.toFixed(3)} Y${cy.toFixed(3)}`);
  lines.push(`G1 Z${(-settings.cutDepth).toFixed(3)} F${settings.plungeRate}`);
  lines.push(`G0 Z${settings.safeHeight.toFixed(3)}`);
}

function generateVCarveGCode(shape: Shape, settings: CamSettings, lines: string[]) {
  const charWidth = settings.vBitWidth;
  const depth = calculateVBitDepth(charWidth, settings.vBitAngle);
  const effectiveDepth = Math.min(depth, settings.cutDepth);
  const passCount = Math.ceil(effectiveDepth / settings.passDepth);

  if (shape.type === 'text') {
    const charPaths = textToPathPoints(shape);
    for (const path of charPaths) {
      if (path.length < 2) continue;
      cutPath(path, settings, lines, passCount, true);
    }
    return;
  }

  let pathPoints = shapeToPathPoints(shape);
  if (pathPoints.length < 2) return;
  pathPoints = offsetPath(pathPoints, settings.vBitWidth / 2);
  const isClosed = shape.type === 'rect' || shape.type === 'circle' || (shape.type === 'path' && pathPoints.length > 2);
  cutPath(pathPoints, settings, lines, passCount, isClosed);
}

function cutPath(pathPoints: Point[], settings: CamSettings, lines: string[], passCount: number, isClosed: boolean) {
  for (let pass = 1; pass <= passCount; pass++) {
    const z = -(Math.min(pass * settings.passDepth, settings.cutDepth));
    const startPt = pathPoints[0];

    lines.push(`G0 X${startPt.x.toFixed(3)} Y${startPt.y.toFixed(3)}`);
    lines.push(`G1 Z${z.toFixed(3)} F${settings.plungeRate}`);

    for (let i = 1; i < pathPoints.length; i++) {
      const p = pathPoints[i];
      lines.push(`G1 X${p.x.toFixed(3)} Y${p.y.toFixed(3)} F${settings.feedRate}`);
    }

    if (isClosed) {
      lines.push(`G1 X${startPt.x.toFixed(3)} Y${startPt.y.toFixed(3)} F${settings.feedRate}`);
    }

    lines.push(`G0 Z${settings.safeHeight.toFixed(3)}`);
  }
}

export function parseGCode(lines: string[]): GCodeLine[] {
  const result: GCodeLine[] = [];
  for (const raw of lines) {
    const trimmed = raw.trim();
    if (!trimmed || trimmed.startsWith(';')) {
      result.push({ line: raw, command: 'OTHER' });
      continue;
    }

    const cmdMatch = trimmed.match(/^(G0|G1|G2|G3|M3|M5|M30|G21|G90|G17|G94)\b/i);
    const cmd = (cmdMatch?.[1]?.toUpperCase() || 'OTHER') as GCodeLine['command'];

    const xMatch = trimmed.match(/X(-?[\d.]+)/i);
    const yMatch = trimmed.match(/Y(-?[\d.]+)/i);
    const zMatch = trimmed.match(/Z(-?[\d.]+)/i);
    const fMatch = trimmed.match(/F(-?[\d.]+)/i);
    const sMatch = trimmed.match(/S(-?[\d.]+)/i);

    result.push({
      line: raw,
      command: cmd,
      x: xMatch ? parseFloat(xMatch[1]) : undefined,
      y: yMatch ? parseFloat(yMatch[1]) : undefined,
      z: zMatch ? parseFloat(zMatch[1]) : undefined,
      f: fMatch ? parseFloat(fMatch[1]) : undefined,
      s: sMatch ? parseFloat(sMatch[1]) : undefined,
    });
  }
  return result;
}

export type SimSegment = {
  from: Point;
  to: Point;
  z: number;
  rapid: boolean;
};

export function extractSimSegments(parsed: GCodeLine[]): SimSegment[] {
  const segments: SimSegment[] = [];
  let curX = 0, curY = 0, curZ = 0;

  for (const p of parsed) {
    if (p.command === 'OTHER') continue;
    const nx = p.x ?? curX;
    const ny = p.y ?? curY;
    const nz = p.z ?? curZ;
    const rapid = p.command === 'G0';

    if (p.x !== undefined || p.y !== undefined || p.z !== undefined) {
      segments.push({ from: { x: curX, y: curY }, to: { x: nx, y: ny }, z: nz, rapid });
      curX = nx;
      curY = ny;
      curZ = nz;
    }
  }

  return segments;
}

export function estimateTime(parsed: GCodeLine[], feedRate: number): number {
  let totalDist = 0;
  let curX = 0, curY = 0;

  for (const p of parsed) {
    if (p.command === 'G1' && p.x !== undefined && p.y !== undefined) {
      const dist = Math.sqrt((p.x - curX) ** 2 + (p.y - curY) ** 2);
      totalDist += dist;
      curX = p.x;
      curY = p.y;
    }
  }

  return feedRate > 0 ? totalDist / feedRate * 60 : 0;
}
